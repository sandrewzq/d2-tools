import type { InterfaceLocale, LocaleCopy } from "../types.js";

const dateTimeFormatByLocale: Record<InterfaceLocale, Intl.DateTimeFormat> = {
  "zh-CN": new Intl.DateTimeFormat("zh-CN", { dateStyle: "medium", timeStyle: "short" }),
  "en-US": new Intl.DateTimeFormat("en-US", { dateStyle: "medium", timeStyle: "short" })
};

function formatDateTime(locale: InterfaceLocale, value: string): string {
  const date = new Date(value);
  return Number.isFinite(date.getTime()) ? dateTimeFormatByLocale[locale].format(date) : value;
}

